"""Hand-authored Thai call-centre language, organised by dialogue phase and scenario.

WHAT THIS IS, STATED PLAINLY, BECAUSE IT BOUNDS EVERY NUMBER THE SET PRODUCES:

These are templates written by hand in the register of a Thai telecom call centre. A
composer draws from them to build each call. They are NOT transcripts of real calls, and
nobody should quote a WER measured on this set as a production WER. What the set is good
for is *relative* comparison under controlled acoustic conditions -- arm A against arm B
on identical audio, and the same arm across the ten mechanism families -- which is exactly
the comparison the rest of this repository is built to make.

The register is taken from the production system prompt at
``config/sentiment_qa/system_prompt/system_prompt.txt``: primary language Thai, industry
telecommunications, True and dtac as the service providers, and the retention / downsell /
MNP triad that the QA rubric scores.

Politeness slots, filled per speaker gender by the composer:
    {p}     ครับ / ค่ะ      statement particle
    {pq}    ครับ / คะ       question particle
    {self}  ผม / ดิฉัน      first person

Entity slots are filled with SPOKEN forms by the composer (see thai_num.py); the canonical
digit form is recorded separately as the entity value.

MONEY SLOTS ARE NOT INTERCHANGEABLE. There are four, and using the wrong one produces a
call that contradicts itself:

    {amount}        what the customer pays TODAY -- the figure they call too expensive
    {amount_offer}  the new, strictly LOWER price the agent offers    (< {amount})
    {amount2}       a strictly HIGHER figure, for "up from" comparisons  (> {amount})
    {amount3}       a small figure: a discount, a fee, a per-month saving

A single {amount} was used for all four once. The result was an agent answering "I pay 999
a month and it is too much" by recommending a package at 999 a month, then approving "an
additional 999 baht per month discount" -- the entire bill, free.
"""

