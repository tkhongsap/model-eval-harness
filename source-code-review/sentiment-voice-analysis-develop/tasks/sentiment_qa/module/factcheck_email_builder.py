"""Build the styled HTML email notifying recipients of a fact-check evaluation run."""

from __future__ import annotations

import pandas as pd

METRIC_LABELS = {
    # "accuracy": "Accuracy",
    "f1_score": "F1 Score",
}
DEFAULT_BASELINE_PERCENT = 80.0
# Per-label acceptance baseline (fraction), keyed by GT_FIELD_MAPPING label. Reference values
# supplied by the QA team; "omotenashi" is excluded from scoring but kept here for display.
LABEL_BASELINE_REFERENCE = {
    "greeting_standard": 0.822,
    "manners": 0.996,
    "enthusiasm": 0.984,
    "communication_skill": 0.98,
    "ending_standard": 0.918,
    "data_privacy": 0.978,
    "legal_verification": 0.98,
    "company_verification": 0.882,
    "sla_notification": 0.876,
    "transfer_standard": 0.974,
    "problem_understanding": 1.0,
    "compensation": 0.934,
    "hold_standard": 0.806,
    "wrap_up": 0.916,
    "beyond_scope_support": 0.972,
    "self_service": 0.888,
    "case_ownership": 0.924,
    "contact_confirm": 0.928,
    "omotenashi": 0.532,
    "retention": 0.948,
    "downsell": 0.948,
    "mnp": 0.976,
    "upselling": 0.912,
}

_TABLE_STYLE = """
<style>
    .fc-table { border-collapse: collapse; font-family: Arial; font-size: 11px; border: 1px solid #444; }
    .fc-table th { background-color: #0078d4; color: white; border: 1px solid #ffffff; padding: 4px 8px;
        text-align: center; }
    .fc-table td { border: 1px solid #ccc; padding: 4px 6px; text-align: center; }
    .fc-table .gray-row td { background-color: #f3f3f3; }
    .fc-table .dimension-col { text-align: left !important; font-weight: bold; min-width: 100px; }
</style>
"""


class FactCheckEmailBuilder:
    """Render subject/body HTML for a fact-check evaluation run (`EVALUATION_OUTPUT_SCHEMA` rows)."""

    def build_subject(self, eval_df: pd.DataFrame) -> str:
        """Return the email subject, tagged with this run's execution date.

        Args:
            eval_df: This run's evaluation rows (`EVALUATION_OUTPUT_SCHEMA`).

        Returns:
            The email subject line.
        """
        execution_date = str(eval_df.iloc[0]["created_datetime"])[:10] if not eval_df.empty else "N/A"
        return f"[AI Report] [AI-QA] Fact Check Evaluation - {execution_date}"

    def build_body(self, eval_df: pd.DataFrame) -> str:
        """Compose the full HTML body: style block + run-metadata header + metrics table + footer.

        Args:
            eval_df: This run's evaluation rows (`EVALUATION_OUTPUT_SCHEMA`).

        Returns:
            The full HTML email body.
        """
        run_meta = self._build_run_meta(eval_df)
        header = self._build_header(run_meta)
        table = self._build_metrics_table(eval_df)
        return f"""
        Dear User,<br>
        {_TABLE_STYLE}
        <br>
        Sentiment Analysis QA - Fact Check Evaluation Report <br>
        {header}
        <br>
        {table}
        <br>

        Best Regards,<br>
        [This is automatic message generated by AI - Do Not REPLY]
        """

    def _build_run_meta(self, eval_df: pd.DataFrame) -> dict:
        """Extract run-level metadata from the first row (identical across all rows of one run).

        Args:
            eval_df: This run's evaluation rows (`EVALUATION_OUTPUT_SCHEMA`).

        Returns:
            A dict of gcp_project_id, gcp_project_name, model_version, ground_truth_count,
            prediction_count, and created_datetime.
        """
        if eval_df.empty:
            return {}
        row = eval_df.iloc[0]
        return {
            "gcp_project_id": row.get("gcp_project_id"),
            "gcp_project_name": row.get("gcp_project_name"),
            "model_version": row.get("model_version"),
            "ground_truth_count": row.get("ground_truth_count"),
            "prediction_count": row.get("prediction_count"),
            "created_datetime": row.get("created_datetime"),
        }

    def _build_header(self, run_meta: dict) -> str:
        """Return the metadata header HTML block.

        Args:
            run_meta: Run-level metadata from `_build_run_meta`.

        Returns:
            An HTML fragment summarizing the run.
        """
        return f"""
        Report Date: {run_meta.get("created_datetime", "N/A")} <br>
        Project: {run_meta.get("gcp_project_id", "N/A")} <br>
        Model Version: {run_meta.get("model_version", "N/A")} <br>
        Ground Truth Count: {run_meta.get("ground_truth_count", "N/A")} <br>
        Prediction Count: {run_meta.get("prediction_count", "N/A")} <br>
        """

    def _build_metrics_table(self, eval_df: pd.DataFrame) -> str:
        """Return the metrics `<table>` HTML, grouped by dimension; excludes weighted_avg rows.

        Args:
            eval_df: This run's evaluation rows (`EVALUATION_OUTPUT_SCHEMA`).

        Returns:
            An HTML `<table>` fragment.
        """
        eval_df = eval_df[eval_df["label"] != "weighted_avg"]
        header_cols = "".join(f"<th>{label}</th>" for label in METRIC_LABELS.values())
        rows_html = []
        for dimension, dim_rows in eval_df.groupby("dimension", sort=False):
            for i, (_, row) in enumerate(dim_rows.iterrows()):
                rows_html.append(self._build_metric_row(dimension, row, first=(i == 0), rowspan=len(dim_rows)))
        rows_html_str = "".join(rows_html)
        return (
            f'<table class="fc-table"><thead><tr><th>Dimension</th><th>Label</th><th>Baseline %(UAT)</th>'
            f"{header_cols}</tr></thead><tbody>{rows_html_str}</tbody></table>"
        )

    def _label_baseline_percent(self, label: str) -> float:
        """Return the acceptance baseline for a label, rounded to 2 decimal places, as a percentage.

        Args:
            label: The `label` value of an evaluation row (a `GT_FIELD_MAPPING` key).

        Returns:
            The baseline percentage (e.g. 82.0 for a 0.822 reference fraction).
        """
        fraction = LABEL_BASELINE_REFERENCE.get(label, DEFAULT_BASELINE_PERCENT / 100)
        return round(fraction, 2) * 100

    def _build_metric_row(self, dimension: str, row: pd.Series, first: bool, rowspan: int) -> str:
        """Return a single `<tr>` for one (dimension, label) evaluation row.

        Args:
            dimension: The dimension name for this group of rows.
            row: A single evaluation row (`EVALUATION_OUTPUT_SCHEMA`).
            first: Whether this is the first row of its dimension group (emits the rowspan cell).
            rowspan: Number of rows in this dimension group.

        Returns:
            An HTML `<tr>` fragment.
        """
        dim_cell = f'<td class="dimension-col" rowspan="{rowspan}">{dimension}</td>' if first else ""
        baseline_cell = f"<td>{self._label_baseline_percent(row['label']):.0f}%</td>"
        metric_cells = "".join(f"<td>{row[metric]:.1f}%</td>" for metric in METRIC_LABELS)
        return f"<tr>{dim_cell}<td>{row['label']}</td>{baseline_cell}{metric_cells}</tr>"
