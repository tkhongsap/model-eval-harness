from typing import Optional, List, Literal
from pydantic import BaseModel, ConfigDict, Field, model_validator

class ReasonKeyword(BaseModel):
    model_config = ConfigDict(extra='ignore')

    reason: Literal['network', 'promotion related', 'device promotion related', 'save cost', 'contract end', 'sale upsell problem', 'dissatisfied service', 'post to pre', 'customer reason', 'true point, dtac reward', 'down sell not success', 'other'] = Field(
        ...,
        description="The reason for customer cancellation, must be one of the cancellation categories defined in the prompt.",
    )
    keyword: str = Field(
        ...,
        description="Specific Thai phrases extracted strictly from the customer's speech that support the reason for cancellation.",
    )

class Reasons(BaseModel):
    model_config = ConfigDict(extra='ignore')

    main: ReasonKeyword = Field(
        ...,
        description="The single most critical factor driving the customer's decision (The Root Cause).",
    )
    secondary: Optional[ReasonKeyword] = Field(
        default=None,
        description="The secondary reason representing the Context, Method, or Trigger.",
    )
    third: Optional[ReasonKeyword] = Field(
        default=None,
        description="The third reason for minor complaints or issues mentioned in passing.",
    )

    @model_validator(mode='after')
    def remove_duplicates_and_merge_keywords(self):
        # 1. Check Secondary vs Main
        if self.secondary and self.secondary.reason == self.main.reason:
            # Merge keyword into Main
            self.main.keyword = f"{self.main.keyword}, {self.secondary.keyword}"
            # Remove Secondary
            self.secondary = None

        # 2. Check Third vs Main
        if self.third and self.third.reason == self.main.reason:
            # Merge keyword into Main
            self.main.keyword = f"{self.main.keyword}, {self.third.keyword}"
            # Remove Third
            self.third = None

        # 3. Check Third vs Secondary (only if Secondary still exists)
        if self.secondary and self.third and self.third.reason == self.secondary.reason:
            # Merge keyword into Secondary
            self.secondary.keyword = f"{self.secondary.keyword}, {self.third.keyword}"
            # Remove Third
            self.third = None

        return self

class AdditionalFields(BaseModel):
    model_config = ConfigDict(extra='ignore')

    issue_type: Optional[Literal['Speed', 'Outage', 'Drop', 'Coverage', 'FUP', 'Installation', 'Support', 'Voice Quality']] = Field(
        default=None,
        description="Identify the primary network issue type based on customer's statements. Categories: 'Speed' (slow internet/data throttling), 'Outage' (complete loss of connectivity/service interruptions), 'Drop' (frequent disconnections/unstable connections), 'Coverage' (poor signal/lack of coverage in specific areas), 'FUP' (Fair Usage Policy limits reached/exceeded), 'Installation' (setup/installation problems), 'Support' (inadequate customer support for network problems), 'Voice Quality' (issues with audio quality in communications). If no clear network issue detected, return null. IMPORTANT: When this field is populated, ALL other analysis fields must also be populated.",
    )
    sub_reason: Optional[str] = Field(
        default=None,
        description="When issue_type is identified, provide detailed English explanation of the specific issue the customer is facing (maximum 800 characters). Required when issue_type is not null.",
    )
    problem_statement_list: Optional[List[str]] = Field(
        default_factory=list,
        description="When issue_type is identified, extract the exact Thai sentences or phrases from the customer's statements where they describe the network problem or how it impacts them. Required when issue_type is not null (minimum 1 statement).",
    )
    problem_statement: Optional[str] = Field(
        default=None,
        description="This field will be automatically generated by joining the list of problem statements into a single string."
    )
    churn_probability: Optional[int] = Field(
        default=None,
        description="When issue_type is identified, estimate the probability (0-100) that the customer will churn based on severity of the issue, customer's sentiment, and their statements during the call. Required when issue_type is not null.",
    )
    area_tag_province: Optional[str] = Field(
        default=None,
        description="This field captures the specific province-level location mentioned by the customer during the call. If the customer does not mention a province-level location, this field should be set to None.",
    )
    area_tag_district: Optional[str] = Field(
        default=None,
        description="This field captures the specific district-level location mentioned by the customer during the call. If the customer does not mention a district-level location, this field should be set to None.",
    )
    area_tag_sub_district: Optional[str] = Field(
        default=None,
        description="This field captures the specific sub-district-level location mentioned by the customer during the call. If the customer does not mention a sub-district-level location, this field should be set to None.",
    )
    area_tag_landmark: Optional[str] = Field(
        default=None,
        description="This field captures the specific landmark-level location mentioned by the customer during the call. If the customer does not mention a landmark-level location, this field should be set to None.",
    )
    product_type: Optional[Literal['Postpaid', 'Prepaid', 'TVS', 'TOL']] = Field(
        default=None,
        description="Product type mentioned by the customer during the call. Categories: 'Postpaid' (mobile products/services billed monthly), 'Prepaid' (pay-as-you-go mobile products/services), 'TVS' (True Vision and entertainment media products/services), 'TOL' (True Online or home internet/broadband products/services). Required when issue_type is identified, otherwise null.",
    )

    @model_validator(mode='after')
    def default_null_value(self):
        if self.issue_type is None:
            self.sub_reason = None
            self.problem_statement_list = []
            self.problem_statement = None
            self.churn_probability = None
            self.area_tag_province = None
            self.area_tag_district = None
            self.area_tag_sub_district = None
            self.area_tag_landmark = None
            self.product_type = None

        # Generate problem_statement from problem_statement_list
        if self.problem_statement_list:
            self.problem_statement = ", ".join(self.problem_statement_list)
        else:
            self.problem_statement = None
        
        return self

class OutputValidation(BaseModel):
    model_config = ConfigDict(extra='ignore')

    reasoning: str = Field(
        ...,
        description="Analyze the conversation step-by-step in a logical manner. Consider the customer's tone, the call center agent's responses, and the flow of the conversation. Explain your thought process before concluding the final result.",
    )
    reasons: Reasons = Field(
        ...,
        description="Structured information about the reasons for customer cancellation.",
    )
    call_result: Literal['save', 'churn', 'unknown', 'undefine'] = Field(
        ...,
        description="Determine the final decision of the customer regarding whether they decided to continue using the service or cancel it after retention efforts or alternative offers from the call center agent.",
    )
    call_event_detection: Optional[Literal['Market-Driven Events (เหตุการณ์ทางการตลาด)', 'Crisis & Emergency Events (เหตุการณ์วิกฤตหรือภัยพิบัติ)', 'Campaign-Driven Events (เหตุการณ์ด้านเคมเปญต่างๆของบริษัท)', 'Technology & Service Events (เหตุการณ์ด้านเทคโนโลยี/บริการ)', 'True-DTAC Merger (เหตุการณ์การรวมกิจการของ True และ Dtac)', 'Emerging or Undefined Events (เหตุการณ์ที่ยังไม่สามารถจัดกลุ่มได้)']] = Field(
        default=None,
        description="Determine what event may have influenced the customer's decision to cancel the service.",
    )
    ai_recommendation: Optional[str] = Field(
        default=None,
        description="Analyze the conversation and provide short recommendations to improve customer service and retention strategies based on the identified reasons for cancellation and customer feedback.",
    )
    additional_fields: AdditionalFields = Field(
        ...,
        description="Additional structured information extracted from the conversation.",
    )